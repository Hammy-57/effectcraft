#!/bin/sh
# Rebuild plugin/code.js (what Figma loads) from the shared serializer and the plug-in's main
# thread. A test (`plugin_embeds_the_shared_serializer`) fails when code.js is out of date.
set -e
cd "$(dirname "$0")"
{
  echo "// GENERATED by integrations/figma/build-plugin.sh from serialize.js + plugin/src/main.js. Edit those."
  echo
  cat serialize.js
  echo
  cat plugin/src/main.js
} > plugin/code.js
echo "wrote plugin/code.js"
